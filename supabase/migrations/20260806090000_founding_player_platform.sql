  moderation_status text not null default 'pending' check (moderation_status in ('pending','approved','rejected','suspended')),
  fair_play_status text not null default 'good' check (fair_play_status in ('good','review','restricted')),
  profile_completion smallint not null default 0 check (profile_completion between 0 and 100),
