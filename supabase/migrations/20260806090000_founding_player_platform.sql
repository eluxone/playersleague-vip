create table if not exists public.plvip_badges (
  id uuid primary key default gen_random_uuid(),
  slug citext not null unique,
  name text not null,
  description text not null,
  icon text not null default '◆',
  category text not null default 'community',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.plvip_player_badges (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.plvip_player_profiles(id) on delete cascade,
  badge_id uuid not null references public.plvip_badges(id) on delete cascade,
  awarded_at timestamptz not null default now(),
  awarded_by uuid references auth.users(id),
  note text,
  unique(profile_id,badge_id)
);

create table if not exists public.plvip_challenges (
  id uuid primary key default gen_random_uuid(),
  slug citext not null unique,
  title text not null,
  summary text not null,
  instructions text not null,
  points_reward integer not null default 0 check (points_reward between 0 and 100000),
  status text not null default 'draft' check (status in ('draft','open','closed','archived')),
  opens_at timestamptz,
  closes_at timestamptz,
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  check (closes_at is null or opens_at is null or closes_at > opens_at)
);

create table if not exists public.plvip_challenge_submissions (
  id uuid primary key default gen_random_uuid(),
  challenge_id uuid not null references public.plvip_challenges(id) on delete cascade,
  profile_id uuid not null references public.plvip_player_profiles(id) on delete cascade,
  response_text text not null,
  evidence_url text,
  status text not null default 'submitted' check (status in ('submitted','approved','rejected','needs_review')),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id),
  unique(challenge_id,profile_id)
);

create table if not exists public.plvip_points_ledger (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.plvip_player_profiles(id) on delete cascade,
  amount integer not null check (amount between -100000 and 100000),
  reason text not null,
  source_type text not null default 'admin',
  source_id uuid,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  unique(profile_id,source_type,source_id)
);

create table if not exists public.plvip_announcements (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  body text not null,
  status text not null default 'draft' check (status in ('draft','published','archived')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

create index if not exists plvip_profiles_public_idx on public.plvip_player_profiles(moderation_status,is_public,founding_player_number);
create index if not exists plvip_points_profile_idx on public.plvip_points_ledger(profile_id,created_at desc);
create index if not exists plvip_challenges_public_idx on public.plvip_challenges(published,status,opens_at);
create index if not exists plvip_submissions_profile_idx on public.plvip_challenge_submissions(profile_id,submitted_at desc);

create or replace function public.plvip_set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.plvip_calculate_profile_completion()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  completed integer := 0;
begin
  if nullif(trim(new.display_name),'') is not null then completed := completed + 15; end if;
  if nullif(trim(new.country),'') is not null then completed := completed + 10; end if;
  if nullif(trim(new.bio),'') is not null then completed := completed + 15; end if;
  if nullif(trim(new.avatar_url),'') is not null then completed := completed + 15; end if;
  if coalesce(array_length(new.main_games,1),0) > 0 then completed := completed + 20; end if;
  if coalesce(array_length(new.platforms,1),0) > 0 then completed := completed + 15; end if;
  if nullif(trim(new.play_style),'') is not null then completed := completed + 5; end if;
  if nullif(trim(new.social),'') is not null then completed := completed + 5; end if;
  new.profile_completion := completed;
  new.updated_at := now();
  return new;
end;
$$;

