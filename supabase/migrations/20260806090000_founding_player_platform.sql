create or replace function public.plvip_award_founding_badge()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  founding_badge uuid;
begin
  select id into founding_badge from public.plvip_badges where slug='founding-player' limit 1;
  if founding_badge is not null then
    insert into public.plvip_player_badges(profile_id,badge_id,note)
