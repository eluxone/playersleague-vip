create or replace function public.plvip_public_players(search_text text default null, result_limit integer default 60)
returns table(
  username citext,
  display_name text,
  avatar_url text,
  country text,
  bio text,
  main_games text[],
  platforms text[],
  play_style text,
  social text,
  founding_player_number bigint,
  profile_completion smallint,
  badge_count bigint,
  total_points bigint
)
language sql
stable
security definer
set search_path = public
as $$
  select
    p.username,p.display_name,p.avatar_url,p.country,p.bio,p.main_games,p.platforms,
    p.play_style,p.social,p.founding_player_number,p.profile_completion,
    count(distinct pb.badge_id)::bigint,
    coalesce(sum(distinct case when l.id is not null then l.amount else 0 end),0)::bigint
  from public.plvip_player_profiles p
  left join public.plvip_player_badges pb on pb.profile_id=p.id
  left join public.plvip_points_ledger l on l.profile_id=p.id
  where p.is_public=true and p.moderation_status='approved'
    and (
      nullif(trim(search_text),'') is null
      or p.username::text ilike '%'||trim(search_text)||'%'
      or p.display_name ilike '%'||trim(search_text)||'%'
      or coalesce(p.country,'') ilike '%'||trim(search_text)||'%'
      or array_to_string(p.main_games,' ') ilike '%'||trim(search_text)||'%'
    )
  group by p.id
  order by p.founding_player_number asc
  limit greatest(1,least(coalesce(result_limit,60),100));
$$;

create or replace function public.plvip_public_leaderboard(result_limit integer default 100)
returns table(
  rank bigint,
  username citext,
  display_name text,
  avatar_url text,
  country text,
  founding_player_number bigint,
  total_points bigint,
  badge_count bigint
)
language sql
stable
security definer
set search_path = public
as $$
  with scores as (
    select
      p.id,p.username,p.display_name,p.avatar_url,p.country,p.founding_player_number,
      coalesce(sum(l.amount),0)::bigint as total_points,
      count(distinct pb.badge_id)::bigint as badge_count
    from public.plvip_player_profiles p
    left join public.plvip_points_ledger l on l.profile_id=p.id
    left join public.plvip_player_badges pb on pb.profile_id=p.id
    where p.is_public=true and p.moderation_status='approved'
    group by p.id
  )
  select
    dense_rank() over(order by total_points desc,badge_count desc,founding_player_number asc),
    username,display_name,avatar_url,country,founding_player_number,total_points,badge_count
  from scores
  order by total_points desc,badge_count desc,founding_player_number asc
  limit greatest(1,least(coalesce(result_limit,100),100));
$$;

create or replace function public.plvip_public_profile(profile_username text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  result jsonb;
begin
  select jsonb_build_object(
    'profile',jsonb_build_object(
      'username',p.username,
      'displayName',p.display_name,
      'avatarUrl',p.avatar_url,
      'country',p.country,
      'bio',p.bio,
      'mainGames',p.main_games,
      'platforms',p.platforms,
      'playStyle',p.play_style,
      'social',p.social,
      'foundingPlayerNumber',p.founding_player_number,
      'profileCompletion',p.profile_completion,
      'joinedAt',p.created_at
    ),
    'badges',coalesce((
      select jsonb_agg(jsonb_build_object('slug',b.slug,'name',b.name,'description',b.description,'icon',b.icon,'awardedAt',pb.awarded_at) order by pb.awarded_at)
      from public.plvip_player_badges pb
      join public.plvip_badges b on b.id=pb.badge_id and b.active=true
      where pb.profile_id=p.id
    ),'[]'::jsonb),
    'totalPoints',coalesce((select sum(amount) from public.plvip_points_ledger where profile_id=p.id),0),
    'approvedChallenges',(select count(*) from public.plvip_challenge_submissions where profile_id=p.id and status='approved')
  ) into result
  from public.plvip_player_profiles p
  where p.username=profile_username::citext and p.is_public=true and p.moderation_status='approved'
  limit 1;
  return result;
end;
$$;

create or replace function public.plvip_admin_moderate_profile(target_profile uuid,new_status text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.current_user_is_admin() then raise exception 'Not authorised'; end if;
  if new_status not in ('pending','approved','rejected','suspended') then raise exception 'Invalid status'; end if;
  update public.plvip_player_profiles
  set moderation_status=new_status,
      approved_at=case when new_status='approved' then now() else approved_at end,
      approved_by=case when new_status='approved' then auth.uid() else approved_by end,
      updated_at=now()
  where id=target_profile;
end;
$$;

create or replace function public.plvip_admin_award_badge(target_profile uuid,badge_slug text,award_note text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare target_badge uuid;
begin
  if not public.current_user_is_admin() then raise exception 'Not authorised'; end if;
  select id into target_badge from public.plvip_badges where slug=badge_slug::citext and active=true;
  if target_badge is null then raise exception 'Badge not found'; end if;
  insert into public.plvip_player_badges(profile_id,badge_id,awarded_by,note)
  values(target_profile,target_badge,auth.uid(),left(nullif(trim(award_note),''),500))
  on conflict(profile_id,badge_id) do update set awarded_at=now(),awarded_by=auth.uid(),note=excluded.note;
end;
$$;

create or replace function public.plvip_admin_add_points(target_profile uuid,point_amount integer,point_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.current_user_is_admin() then raise exception 'Not authorised'; end if;
  if point_amount=0 or abs(point_amount)>100000 then raise exception 'Invalid points'; end if;
  insert into public.plvip_points_ledger(profile_id,amount,reason,source_type,created_by)
  values(target_profile,point_amount,left(trim(point_reason),300),'admin',auth.uid());
end;
$$;

create or replace function public.plvip_admin_review_submission(target_submission uuid,new_status text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  submission_record public.plvip_challenge_submissions%rowtype;
  reward integer;
  badge uuid;
begin
  if not public.current_user_is_admin() then raise exception 'Not authorised'; end if;
  if new_status not in ('approved','rejected','needs_review') then raise exception 'Invalid status'; end if;
  select * into submission_record from public.plvip_challenge_submissions where id=target_submission for update;
  if not found then raise exception 'Submission not found'; end if;
  update public.plvip_challenge_submissions set status=new_status,reviewed_at=now(),reviewed_by=auth.uid() where id=target_submission;
  if new_status='approved' then
    select points_reward into reward from public.plvip_challenges where id=submission_record.challenge_id;
    insert into public.plvip_points_ledger(profile_id,amount,reason,source_type,source_id,created_by)
    values(submission_record.profile_id,coalesce(reward,0),'Approved community challenge','challenge',submission_record.id,auth.uid())
    on conflict(profile_id,source_type,source_id) do nothing;
    select id into badge from public.plvip_badges where slug='first-challenge';
    if badge is not null then
      insert into public.plvip_player_badges(profile_id,badge_id,awarded_by,note)
      values(submission_record.profile_id,badge,auth.uid(),'Awarded for an approved community challenge.')
      on conflict do nothing;
    end if;
  end if;
end;
$$;

